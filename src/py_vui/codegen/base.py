"""Code-generation contract shared by every adapter."""

from __future__ import annotations

import ast
from abc import ABC, abstractmethod
from dataclasses import dataclass, field

from py_vui.codegen.merge_regions import render_handlers_module
from py_vui.core.document import ProjectDocument
from py_vui.core.model import Project
from py_vui.core.registry import requirements_for

HEADER = "# This code is generated by py_vui: https://github.com/dfunani/py_vui"


@dataclass(frozen=True)
class GeneratedFile:
    #: path relative to the output directory (posix separators)
    path: str
    content: str
    #: False => never overwrite if it already exists (user-owned files such as custom.py)
    overwrite: bool = True
    #: bytes payload for assets (content ignored when set)
    data: bytes | None = None


@dataclass
class GenOptions:
    #: "project": main.py + ui.py + handlers.py …  | "single": one self-contained script
    layout: str = "project"
    #: keep user edits made inside handlers.py custom regions on regeneration
    preserve_user_code: bool = False
    #: existing file contents by relative path (for merge)
    existing: dict[str, str] = field(default_factory=dict)
    #: include a bundled README
    readme: bool = True


class Adapter(ABC):
    framework: str = ""
    label: str = ""

    @abstractmethod
    def generate(self, project: Project, options: GenOptions) -> list[GeneratedFile]:
        """Return every file of the generated app."""

    def requirements(self, project: Project) -> list[str]:
        doc = ProjectDocument(project)
        types = {n.type for n in doc.project.nodes.values()}
        reqs = set(self.base_requirements()) | set(requirements_for(types, self.framework))
        reqs.update(project.extra_requirements)
        if any(n.props.get("image") or n.props.get("source") for n in project.nodes.values()
               if n.type in {"label", "button", "image"}):
            reqs.update(self.image_requirements())
        return sorted(reqs, key=str.lower)

    def base_requirements(self) -> list[str]:
        return []

    def image_requirements(self) -> list[str]:
        return []


_ADAPTERS: dict[str, Adapter] = {}


def register_adapter(adapter: Adapter) -> Adapter:
    _ADAPTERS[adapter.framework] = adapter
    return adapter


def get_adapter(framework: str) -> Adapter:
    _load_builtin_adapters()
    try:
        return _ADAPTERS[framework]
    except KeyError as exc:
        msg = f"no code generator for framework {framework!r}"
        raise KeyError(msg) from exc


def adapters() -> dict[str, Adapter]:
    _load_builtin_adapters()
    return dict(_ADAPTERS)


def _load_builtin_adapters() -> None:
    if _ADAPTERS:
        return
    import importlib

    for mod in (
        "py_vui.codegen.tk_adapter",
        "py_vui.codegen.ctk_adapter",
        "py_vui.codegen.qt_adapter",
        "py_vui.codegen.kivy_adapter",
    ):
        try:
            importlib.import_module(mod)
        except ModuleNotFoundError as exc:  # adapter not installed/finished
            if exc.name != mod:
                raise


def generate(project: Project, options: GenOptions | None = None) -> list[GeneratedFile]:
    return get_adapter(project.framework).generate(project, options or GenOptions())


def handlers_file(project: Project, options: GenOptions) -> GeneratedFile:
    """The shared ``handlers.py`` (user callbacks) used by all adapters in project layout."""
    existing = options.existing.get("handlers.py") if options.preserve_user_code else None
    return GeneratedFile("handlers.py", render_handlers_module(project, existing))


def check_syntax(files: list[GeneratedFile]) -> list[str]:
    """Return a list of 'path: error' strings for any generated .py file that doesn't parse."""
    errors = []
    for f in files:
        if f.path.endswith(".py") and f.data is None:
            try:
                ast.parse(f.content, f.path)
            except SyntaxError as exc:
                errors.append(f"{f.path}:{exc.lineno}: {exc.msg}")
    return errors


# --------------------------------------------------------------------------- plugin hook
@dataclass
class EmitContext:
    """Passed to a plugin emitter. The adapter places/styles the widget afterwards."""

    project: Project
    node: object  # py_vui.core.model.Node
    var: str  # identifier the emitted code must assign the widget to
    parent: str  # identifier of the parent widget/container
    framework: str


@dataclass
class EmitResult:
    #: module-level import lines, e.g. ["import foo"]
    imports: list[str] = field(default_factory=list)
    #: statements (unindented) that create ``ctx.var`` as a child of ``ctx.parent``
    lines: list[str] = field(default_factory=list)
    requirements: list[str] = field(default_factory=list)


_PLUGIN_EMITTERS: dict[tuple[str, str], object] = {}


def register_plugin_emitter(widget_type: str, framework: str, fn) -> None:
    """Register code emission for a (plugin) widget type on one framework."""
    _PLUGIN_EMITTERS[(widget_type, framework)] = fn


def plugin_emitter(widget_type: str, framework: str):
    return _PLUGIN_EMITTERS.get((widget_type, framework))
