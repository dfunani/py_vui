def test_absolute_anchors_on_resize(run):
    p = mk({"width": 400, "height": 300})
    add(p, "button", x=10, y=10, w=80, h=30, name="TL")
    br = add(p, "button", x=300, y=250, w=80, h=30, name="BR")
    br.anchors = Anchors(left=False, top=False, right=True, bottom=True)
    st = add(p, "entry", x=10, y=100, w=380, h=30, name="Stretch")
    st.anchors = Anchors(left=True, top=True, right=True, bottom=False)
    ct = add(p, "button", x=170, y=135, w=60, h=30, name="Centre")
    ct.anchors = Anchors(left=False, top=False, right=False, bottom=False)
    app = run(p)
    app.expect(app.W["tl"], 10, 10, 80, 30)
    app.expect(app.W["br"], 300, 250, 80, 30)
    app.resize(600, 500)
    # top-left stays put
    app.expect(app.W["tl"], 10, 10, 80, 30)
    # bottom-right follows the new corner: 20px from right, 20px from bottom
    app.expect(app.W["br"], 600 - 20 - 80, 500 - 20 - 30, 80, 30)
    # left+right anchored stretches
    app.expect(app.W["stretch"], 10, 100, 580, 30)
    # unanchored is centred (offset grows by half the delta)
    app.expect(app.W["centre"], 170 + 100, 135 + 100, 60, 30)
    # shrinking works too
    app.resize(300, 200)
    app.expect(app.W["br"], 300 - 20 - 80, 200 - 20 - 30, 80, 30)


