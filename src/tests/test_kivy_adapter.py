@pytest.fixture(scope="session")
def kv_env():
    if not HAVE_KIVY:
        pytest.skip("kivy is not importable in this interpreter")
    if os.environ.get("PY_VUI_KIVY_TESTS") == "0":
        pytest.skip("runtime Kivy tests disabled")
    try:
        from kivy.config import Config

        Config.set("graphics", "window_state", "hidden")
        from kivy.core.window import Window

        if Window is None:
            raise RuntimeError("no Kivy window provider")
        from kivy.base import EventLoop

        EventLoop.idle()
    except Exception as exc:  # pragma: no cover - environment dependent
        pytest.skip(f"cannot create a Kivy window here: {exc}")
    return Window


class Running:
    """A generated app that has been imported and built inside the test process."""

    def __init__(self, project, tmp_path, layout="project", window=None, **opts):
        from kivy.base import EventLoop
        from kivy.core.window import Window
        from kivy.metrics import dp

        self.EventLoop, self.Window, self.dp = EventLoop, Window, dp
        self.project = project
        self.tmp = tmp_path
        files = generate(project, GenOptions(layout=layout, **opts))
        assert check_syntax(files) == []
        for f in files:
            (tmp_path / f.path).write_text(f.content)
        self.files = {f.path: f.content for f in files}
        self.layout = layout
        for name in ("ui", "handlers", "custom", "main"):
            sys.modules.pop(name, None)
        sys.path.insert(0, str(tmp_path))
        self.mod = importlib.import_module("main" if layout == "single" else "ui")
        self.handlers = importlib.import_module("handlers") if layout == "project" else self.mod
        root_node = project.nodes[project.root_id]
        self.design = (root_node.props["width"], root_node.props["height"])
        self.root = self.mod.build_ui()
        self.root.size_hint = (None, None)  # tests drive the size (the app lets Window do it)
        Window.add_widget(self.root)
        self.resize(*self.design)

    @property
    def W(self):
        return self.mod.WIDGETS

    @property
    def calls(self):
        return self.handlers.CALLS

    def names(self):
        return [c[0] for c in self.calls]

    def settle(self, n=3):
        for _ in range(n):
            self.EventLoop.idle()

    def until(self, cond, timeout=3.0):
        """Pump Kivy's clock until ``cond()`` (animations such as Popup.open need real time)."""
        import time

        from kivy.clock import Clock

        end = time.time() + timeout
        while not cond() and time.time() < end:
            time.sleep(0.02)
            Clock.tick()
        assert cond(), "timed out waiting for condition"

    def resize(self, w, h, extra=0):
        self.root.pos = (0, 0)
        self.root.size = (self.dp(w), self.dp(h + extra))
        self.settle()

    def expect(self, widget, x, y, w, h, tol=1.5):
        """Assert ``widget`` sits at design (x, y, w, h) measured from the root's top-left."""
        dp = self.dp
        root = self.root
        got = (widget.x - root.x, root.top - widget.top, widget.width, widget.height)
        want = (dp(x), dp(y), dp(w), dp(h))
        assert got == pytest.approx(want, abs=tol), (got, want)

    def touch(self, widget, kind="tap", button="left", double=False, pos=None):
        from kivy.tests.common import UnitTestTouch

        x, y = widget.to_window(*(pos or widget.center))
        t = UnitTestTouch(x, y)
        t.button = button
        t.is_double_tap = double
        t.touch_down()
        self.settle(1)
        if kind == "tap":
            t.touch_up()
        self.settle(1)
        return t

    def close(self):
        try:
            self.Window.remove_widget(self.root)
        except Exception:
            pass
        for w in list(self.Window.children):
            self.Window.remove_widget(w)
        if str(self.tmp) in sys.path:
            sys.path.remove(str(self.tmp))
        for name in ("ui", "handlers", "custom", "main"):
            sys.modules.pop(name, None)


