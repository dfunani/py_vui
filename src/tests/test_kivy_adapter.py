def mk(root_props: dict | None = None):
    p = new_project("Kv", "kivy")
    if root_props:
        p.nodes[p.root_id].props.update(root_props)
    return p


def add(p, type_id, parent=None, **kw):
    kids = kw.pop("props", {})
    n = make_node(type_id, parent_id=parent or p.root_id, z_index=len(p.nodes), **kw, **kids)
    p.nodes[n.id] = n
    return n


def recorder(p, *names):
    """Handlers that append ``(name, event)`` to ``handlers.CALLS``."""
    p.custom_code = "CALLS = []"
    for name in names:
        p.handlers[name] = HandlerDef(name=name, body=f"CALLS.append(({name!r}, event))")


def files_of(p, **opts):
    files = generate(p, GenOptions(**opts))
    assert check_syntax(files) == []
    return {f.path: f.content for f in files}


