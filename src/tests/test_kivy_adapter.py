def test_flex_grow_adds_share_to_basis_and_follows_resize(run):
    """grow distributes the free space proportionally on top of each child's own size."""
    from py_vui.core.layout_engine import resolve_children

    p = mk()
    c = _flex(p, direction="row", gap=10)
    for pad in ("top", "left", "right", "bottom"):
        setattr(c.layout.padding, pad, 5)
    add(p, "button", parent=c.id, w=40, h=30, name="Fixed")
    a = add(p, "button", parent=c.id, w=40, h=30, name="Ga")
    b = add(p, "button", parent=c.id, w=60, h=30, name="Gb")
    a.flex.grow, b.flex.grow = 1, 3
    app = run(p)
    doc = ProjectDocument(p)
    box = app.W["flex"]
    assert type(box).__name__ == "FloatLayout"
    boxes = resolve_children(doc, c.id)
    for n in doc.children(c.id):
        e = boxes[n.id]
        w = app.W[n.name.lower()]
        got = (w.x - box.x, box.top - w.top, w.width, w.height)
        assert got == pytest.approx(tuple(app.dp(v) for v in (e.x, e.y, e.w, e.h)), abs=1.5)
    # free = 300 - 10 - (40+40+60) - 20 = 130 -> Ga = 40 + 32.5, Gb = 60 + 97.5
    assert app.W["ga"].width == pytest.approx(app.dp(72.5), abs=1.5)
    assert app.W["gb"].width == pytest.approx(app.dp(157.5), abs=1.5)
    box.width = app.dp(400)  # responsive: shares are recomputed
    app.settle()
    assert app.W["gb"].width > app.dp(157.5) and app.W["ga"].width > app.dp(72.5)


@pytest.mark.parametrize("row", [True, False])
def test_flex_wrap_matches_editor(run, row):
    from py_vui.core.layout_engine import resolve_children

    p = mk()
    c = _flex(p, direction="row" if row else "column", gap=6, wrap=True)
    c.box.w, c.box.h = 200, 120
    for pad in ("top", "left", "right", "bottom"):
        setattr(c.layout.padding, pad, 4)
    for i in range(7):
        add(p, "button", parent=c.id, w=50, h=30, name=f"B{i}")
    app = run(p)
    box = app.W["flex"]
    assert type(box).__name__ == "FloatLayout"
    doc = ProjectDocument(p)
    boxes = resolve_children(doc, c.id)
    ys = set()
    for n in doc.children(c.id):
        e = boxes[n.id]
        w = app.W[n.name.lower()]
        got = (w.x - box.x, box.top - w.top, w.width, w.height)
        assert got == pytest.approx(tuple(app.dp(v) for v in (e.x, e.y, e.w, e.h)), abs=1.5)
        ys.add(round(got[1] if row else got[0]))
    assert len(ys) > 1  # really wrapped onto several lines/columns
    box.size = (app.dp(400), app.dp(120))  # a wider container fits more per line
    app.settle()
    wider = {round(box.top - app.W[n.name.lower()].top) for n in doc.children(c.id)}
    assert len(wider) <= len(ys)


