def _flex(p, parent=None, **layout):
    c = add(p, "frame", parent=parent, x=0, y=0, w=300, h=200, name="Flex")
    for k, v in layout.items():
        setattr(c.layout, k, v)
    c.layout.mode = "flex"
    return c


