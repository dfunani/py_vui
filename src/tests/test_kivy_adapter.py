@pytest.mark.parametrize("layout", ["project", "single"])
def test_app_runs_end_to_end_in_subprocess(kv_env, tmp_path, layout):
    """Import the generated entry point in a fresh interpreter and start/stop the real App."""
    p = mk({"title": "E2E"})
    recorder(p, "on_go")
    add(p, "button", x=10, y=10, w=100, h=40, name="Go").events["click"] = "on_go"
    for f in generate(p, GenOptions(layout=layout)):
        (tmp_path / f.path).write_text(f.content)
    script = tmp_path / "_drive.py"
    script.write_text(
        "import os, sys\n"
        "sys.path.insert(0, os.getcwd())\n"
        "from kivy.config import Config\n"
        "Config.set('graphics', 'window_state', 'hidden')\n"
        "import main\n"
        "from kivy.clock import Clock\n"
        "app = main.MainApp()\n"
        "def stop(dt):\n"
        "    print('ROOT', type(app.root).__name__)\n"
        "    app.stop()\n"
        "Clock.schedule_once(stop, 0.4)\n"
        "app.run()\n"
        "print('DONE')\n")
    env = {**os.environ, "KIVY_NO_ARGS": "1", "KIVY_NO_CONSOLELOG": "1"}
    res = subprocess.run([sys.executable, "-I", str(script)], cwd=tmp_path, env=env,
                         capture_output=True, text=True, timeout=120, check=False)
    assert res.returncode == 0, res.stdout + res.stderr
    assert "ROOT FloatLayout" in res.stdout and "DONE" in res.stdout


