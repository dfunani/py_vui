@pytest.mark.tk
def test_events_fire_handlers(tmp_path):
    need_ctk()
    res = run_app(tmp_path, gen(project()), """
        def fired(action):
            del log[:]
            action()
            root.update()
            return list(log)

        def ev(widget, seq):
            kw = {"x": 2, "y": 2} if "Button" in seq else {}
            return fired(lambda: widget.event_generate(seq, **kw))

        result["button"] = fired(W["go_abs"].invoke)
        result["tool"] = fired(W["tool_abs"].invoke)
        result["label"] = ev(W["label_abs"]._canvas, "<Button-1>")
        result["label_dbl"] = ["on_dbl"] if "on_dbl" in W["label_abs"]._canvas.bind(
            "<Double-Button-1>")  else []
        result["button_right"] = ev(W["go_abs"]._canvas, "<Button-3>")
        result["frame"] = ev(W["card_abs"]._canvas, "<Button-1>")
        result["canvas_paint"] = ev(W["board_abs"], "<Configure>")
        result["check"] = fired(W["agree_abs"].toggle)
        result["radio"] = fired(W["choice_a_abs"].invoke)
        result["switch"] = fired(W["power_abs"].toggle)
        result["entry"] = fired(lambda: W["field_abs"].insert(0, "x"))  # programmatic edit
        result["entry_value"] = W["field_abs"].get()
        result["slider"] = fired(lambda: ui.VARS["level_abs"].set(35))
        result["dial"] = fired(lambda: W["knob_abs"].set(60, notify=True))
        result["spin"] = fired(lambda: W["count_abs"].step_by(1))
        result["spin_value"] = W["count_abs"].get()
        result["combo"] = fired(lambda: ui.VARS["pick_abs"].set("c"))
        result["seg"] = fired(lambda: ui.VARS["seg_abs"].set("One"))
        result["list"] = fired(lambda: (W["names_abs"].selection_set(1),
                                        W["names_abs"].event_generate("<<ListboxSelect>>")))
        result["time"] = fired(lambda: W["clock_abs"].vars[0].set("09"))
        result["text"] = fired(lambda: W["notes_abs"].insert("end", "!"))
        result["tab"] = fired(lambda: W["tabview_abs"]._segmented_button_callback("One"))
        result["tab_now"] = W["tabview_abs"].get()
        result["win_resize"] = fired(lambda: root.event_generate("<Configure>"))
    """)
    assert res["button"] == ["on_click"] and res["tool"] == ["on_click"]
    assert "on_click" in res["label"] and "on_dbl" in res["label_dbl"]
    assert "on_right" in res["button_right"] and "on_click" in res["frame"]
    assert "on_paint" in res["canvas_paint"]
    for key in ("check", "radio", "switch"):
        assert res[key] == ["on_toggle"], key
    assert "on_change" in res["entry"] and res["entry_value"] == "x"
    for key in ("slider", "dial", "spin", "combo", "seg", "time", "text"):
        assert "on_change" in res[key], key
    assert res["spin_value"] == 1.0 or res["spin_value"] == 3.0
    assert "on_select" in res["list"]
    assert res["tab"] == ["on_tab"] and res["tab_now"] == "One"
    assert "on_resize" in res["win_resize"]


