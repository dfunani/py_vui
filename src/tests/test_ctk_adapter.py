@pytest.mark.tk
def test_absolute_geometry_matches_design(tmp_path):
    need_ctk()
    p = project()
    panel = next(n for n in p.nodes.values() if n.name == "Panel abs")
    kids = [n for n in p.nodes.values() if n.parent_id == panel.id and n.type != "fancy_widget"]
    names = ProjectDocument(p).variable_names()
    res = run_app(tmp_path, gen(p), """
        for n in [n for n in W if n.endswith("_abs")]:
            result[n] = geometry(outer(W[n]))
    """)
    checked = 0
    for node in kids:
        x, y, w, h = res[names[node.id]]
        if node.type in ("map_view", "chart", "video_player", "pandas_table", "calendar",
                         "time_picker", "color_picker", "time_entry", "date_entry"):
            assert (x, y) == (round(node.box.x), round(node.box.y))  # plugin widgets: position
            continue
        assert (x, y) == (round(node.box.x), round(node.box.y)), (node.name, x, y)
        assert abs(w - node.box.w) <= 2 and abs(h - node.box.h) <= 2, (node.name, w, h, node.box)
        checked += 1
    assert checked > 25


def _flex(**layout):
    p = new_project("Flex", FW)
    root = p.nodes[p.root_id]
    root.props.update(width=600, height=300)
    root.layout.mode, root.layout.direction = "flex", "row"
    root.layout.gap, root.layout.align = 10, "start"
    for k, v in layout.items():
        setattr(root.layout, k, v)
    for i, grow in enumerate((0, 1, 2)):
        b = make_node("button", parent_id=p.root_id, name=f"B{i}", z_index=i, w=100, h=30)
        b.flex.grow = grow
        p.nodes[b.id] = b
    return p


