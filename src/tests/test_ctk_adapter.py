def _gaps_project():
    p = new_project("Gaps", FW)
    root = p.nodes[p.root_id]
    root.props.update(width=600, height=500)

    def add(type_id, name, parent, **props):
        n = make_node(type_id, parent_id=parent, name=name, z_index=len(p.nodes), **props)
        p.nodes[n.id] = n
        return n

    slider = add("slider", "Vol", p.root_id, value=40, show_value=True)
    slider.box.x, slider.box.y, slider.box.w, slider.box.h = 10, 10, 300, 30
    bar = add("progressbar", "Load", p.root_id, value=25, show_text=True)
    bar.box.x, bar.box.y, bar.box.w, bar.box.h = 10, 60, 300, 20
    tool = add("tool_button", "Bold", p.root_id, checkable=True, text="B")
    tool.box.x, tool.box.y = 10, 100
    tool.events["click"] = "on_click"
    scroll = add("scroll_frame", "Both", p.root_id, orientation="both")
    scroll.box.x, scroll.box.y, scroll.box.w, scroll.box.h = 10, 150, 200, 120
    inner = add("button", "Wide", scroll.id)
    inner.box.x, inner.box.y, inner.box.w = 5, 5, 600
    text = add("text", "Memo", p.root_id, placeholder="Write here")
    text.box.x, text.box.y = 250, 100
    text.events["change"] = "on_change"
    for name in ("on_click", "on_change"):
        p.handlers[name] = HandlerDef(name=name, body=f"LOG.append({name!r})")
    p.custom_code = "LOG = []"
    return p


