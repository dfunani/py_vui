def test_project_structure_and_handlers():
    p = project()
    files = by_path(gen(p))
    tree = ast.parse(files["ui.py"])
    funcs = {n.name for n in tree.body if isinstance(n, ast.FunctionDef)}
    assert {"build_ui", "open_prefs", "open_splash", "configure_styles"} <= funcs
    used = {n.attr for n in ast.walk(tree)
            if isinstance(n, ast.Attribute) and isinstance(n.value, ast.Name)
            and n.value.id == "handlers"}
    assert used and used <= set(p.handlers)
    single = by_path(gen(p, "single"))["main.py"]
    assert set(HANDLERS) <= {n.name for n in ast.parse(single).body
                             if isinstance(n, ast.FunctionDef)}
    assert "import handlers" not in single


