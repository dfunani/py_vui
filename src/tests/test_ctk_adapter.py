@pytest.mark.parametrize("layout", ["project", "single"])
def test_generated_files_parse(layout):
    files = gen(project(), layout)
    assert check_syntax(files) == []
    paths = [f.path for f in files]
    if layout == "single":
        assert paths[0] == "main.py" and "ui.py" not in paths
    else:
        assert {"main.py", "ui.py", "handlers.py", "custom.py", "requirements.txt",
                "README.md"} <= set(paths)
    for f in files:
        if f.path in ("main.py", "ui.py"):
            assert f.content.startswith("# This code is generated by py_vui")


